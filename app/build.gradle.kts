androidComponents {
    onVariants { variant ->
        val flavorName = variant.productFlavors.firstOrNull { it.first == "language" }?.second
        if (flavorName != null) {
            val variantName = variant.name.uppercaseFirst()
            val assetFiles = requiredModelAssets.map { layout.projectDirectory.file("src/$flavorName/assets/$it") }
            val validateAssets = tasks.register("validate${variantName}PpOcrV3Assets") {
                group = "verification"
                description = "Validates PP-OCRv3 model assets for the ${variant.name} variant."
                inputs.files(assetFiles)

                doLast {
                    val missing = assetFiles.map { it.asFile }.filterNot { it.isFile && it.length() > 0L }
                    if (missing.isNotEmpty()) {
                        val message = buildString {
                            appendLine("Missing PP-OCRv3 model assets for ${variant.name}.")
                            appendLine("Run:")
                            appendLine("  python -I scripts\\prepare_ppocrv3_assets.py --profile $flavorName --slim")
                            appendLine("Missing assets:")
                            missing.forEach { appendLine("  - ${it.relativeTo(rootDir).invariantSeparatorsPath}") }
                        }
                        throw GradleException(message)
                    }
                }
            }
            tasks.matching { it.name == "merge${variantName}Assets" }.configureEach {
                dependsOn(validateAssets)
            }
        }

        variant.outputs.forEach { output ->
            val architecture = output.filters.find {
                it.filterType == FilterConfiguration.FilterType.ABI
            }?.identifier ?: "universal"
            val outputFileNameProperty = output.javaClass.methods.firstOrNull {
                it.name == "getOutputFileName" && it.parameterTypes.isEmpty()
            }?.invoke(output) as? Property<*>

            @Suppress("UNCHECKED_CAST")
            (outputFileNameProperty as? Property<String>)?.set(
                output.versionName.map { versionName ->
                    val version = versionName.replace("\\s".toRegex(), "-")
                    val extension = utils.FILE_EXTENSION_APK
                    "${rootProject.name}-v$version-$flavorName-$architecture.$extension".lowercase()
                }
            )
        }
    }
}

